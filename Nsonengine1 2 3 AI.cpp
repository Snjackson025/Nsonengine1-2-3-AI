#include <iostream>
#include <fstream>
#include <string>
#include <vector>
#include <filesystem>
#include <sstream>
#include <cctype>

namespace fs = std::filesystem;

namespace NsonEngine {

struct GeneratedFile {
    std::string name;
    std::string language;
    std::string path;
};

class CodeValidator {
public:
    static bool ValidName(const std::string& name) {
        if (name.empty() ||
            !(std::isalpha(static_cast<unsigned char>(name[0])) ||
              name[0] == '_')) {
            return false;
        }

        for (unsigned char c : name) {
            if (!std::isalnum(c) && c != '_')
                return false;
        }

        return true;
    }
};

class FileMaker {
public:
    bool Write(const std::string& path,
               const std::string& content) {
        try {
            fs::path filePath(path);

            fs::create_directories(filePath.parent_path());

            if (fs::exists(filePath)) {
                std::cout << "File already exists: "
                          << path << "\n";
                return false;
            }

            std::ofstream file(filePath);

            if (!file.is_open())
                return false;

            file << content;
            file.close();

            return true;
        }
        catch (const std::exception& error) {
            std::cout << "File error: "
                      << error.what() << "\n";
            return false;
        }
    }
};

class TemplateLibrary {
public:
    static std::string CppMain() {
        return R"(#include <iostream>
#include <string>

int main() {
    std::cout << "Hello from NsonEngine generated code!" << std::endl;
    return 0;
}
)";
    }

    static std::string PythonMain() {
        return R"(def main():
    print("Hello from NsonEngine generated code!")

if __name__ == "__main__":
    main()
)";
    }

    static std::string HTMLMain() {
        return R"(<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>NsonEngine Generated Page</title>
</head>
<body>
    <h1>Hello from NsonEngine!</h1>
    <p>Your generated web page is ready.</p>
</body>
</html>
)";
    }

    static std::string CppHeader(const std::string& name) {
        std::string guard = name + "_H";

        return "#pragma once\n\n"
            "#include <string>\n\n"
            "class " + name + " {\n"
            "public:\n"
            "    " + name + "();\n"
            "    void Execute();\n"
            "};\n";
    }

    static std::string CppImplementation(
        const std::string& name) {

        return "#include \"" + name + ".h\"\n"
            "#include <iostream>\n\n"
            + name + "::" + name + "() = default;\n\n"
            "void " + name + "::Execute() {\n"
            "    std::cout << \""
            + name + " is running.\\n\";\n"
            "}\n";
    }

    static std::string CMake(const std::string& name) {
        return "cmake_minimum_required(VERSION 3.16)\n"
            "project(" + name + " LANGUAGES CXX)\n\n"
            "set(CMAKE_CXX_STANDARD 17)\n"
            "set(CMAKE_CXX_STANDARD_REQUIRED ON)\n\n"
            "add_executable(" + name + " main.cpp)\n";
    }

    static std::string Readme(const std::string& name) {
        return "# " + name + "\n\n"
            "Generated by NsonEngine.\n\n"
            "C++17 project.\n\n"
            "## Build\n\n"
            "cmake -S . -B build\n"
            "cmake --build build\n";
    }
};

class CodeGenerator {
private:
    FileMaker files;
    std::vector<GeneratedFile> history;

    void Record(const std::string& name,
                const std::string& language,
                const std::string& path) {
        history.push_back({name, language, path});
    }

public:
    bool GenerateCpp(const std::string& name) {
        if (!CodeValidator::ValidName(name)) {
            std::cout << "Invalid class name.\n";
            return false;
        }

        std::string folder = "NsonOutput/" + name;

        if (fs::exists(folder)) {
            std::cout << "Project folder already exists.\n";
            return false;
        }

        bool header = files.Write(
            folder + "/" + name + ".h",
            TemplateLibrary::CppHeader(name)
        );

        bool source = files.Write(
            folder + "/" + name + ".cpp",
            TemplateLibrary::CppImplementation(name)
        );

        if (header && source) {
            Record(name, "C++", folder);
            std::cout << "C++ class generated successfully.\n";
            return true;
        }

        return false;
    }

    bool GenerateCppProject(const std::string& name) {
        if (!CodeValidator::ValidName(name)) {
            std::cout << "Invalid project name.\n";
            return false;
        }

        std::string folder = "NsonOutput/" + name;

        if (fs::exists(folder)) {
            std::cout << "Project folder already exists.\n";
            return false;
        }

        bool main = files.Write(
            folder + "/main.cpp",
            TemplateLibrary::CppMain()
        );

        bool cmake = files.Write(
            folder + "/CMakeLists.txt",
            TemplateLibrary::CMake(name)
        );

        bool readme = files.Write(
            folder + "/README.md",
            TemplateLibrary::Readme(name)
        );

        if (main && cmake && readme) {
            Record(name, "C++ Project", folder);
            std::cout << "C++ project generated successfully.\n";
            return true;
        }

        return false;
    }

    bool GeneratePython(const std::string& name) {
        if (!CodeValidator::ValidName(name)) {
            std::cout << "Invalid Python filename.\n";
            return false;
        }

        std::string path =
            "NsonOutput/" + name + ".py";

        if (files.Write(path, TemplateLibrary::PythonMain())) {
            Record(name, "Python", path);
            std::cout << "Python file generated successfully.\n";
            return true;
        }

        return false;
    }

    bool GenerateHTML(const std::string& name) {
        if (!CodeValidator::ValidName(name)) {
            std::cout << "Invalid HTML filename.\n";
            return false;
        }

        std::string path =
            "NsonOutput/" + name + ".html";

        if (files.Write(path, TemplateLibrary::HTMLMain())) {
            Record(name, "HTML", path);
            std::cout << "HTML page generated successfully.\n";
            return true;
        }

        return false;
    }

    void DisplayHistory() const {
        std::cout << "\n===== GENERATION HISTORY =====\n";

        if (history.empty()) {
            std::cout << "No generated files this session.\n";
            return;
        }

        for (const auto& item : history) {
            std::cout << item.name
                      << " | " << item.language
                      << " | " << item.path << "\n";
        }
    }

    void DisplayTemplates() const {
        std::cout << "\n===== TEMPLATE LIBRARY =====\n";
        std::cout << "1. C++ Main Program\n";
        std::cout << "2. C++ Class\n";
        std::cout << "3. C++ Project\n";
        std::cout << "4. Python Script\n";
        std::cout << "5. HTML Page\n";
    }
};

class NsonCore {
private:
    CodeGenerator generator;
    bool running = true;

public:
    void Initialize() {
        std::cout << "\n";
        std::cout << "====================================\n";
        std::cout << "          NSON ENGINE\n";
        std::cout << "       COMPUTER CODE MAKER\n";
        std::cout << "====================================\n";

        std::cout << "Code generation system initialized.\n";
        std::cout << "Output directory: NsonOutput/\n";
    }

    void Run() {
        Initialize();

        while (running) {
            DisplayMenu();

            int choice;

            std::cout << "\nSelect operation: ";

            if (!(std::cin >> choice)) {
                std::cin.clear();
                std::cin.ignore(10000, '\n');
                std::cout << "Invalid input.\n";
                continue;
            }

            Process(choice);
        }
    }

private:
    void DisplayMenu() {
        std::cout << "\n====================================\n";
        std::cout << "          NSON ENGINE MENU\n";
        std::cout << "====================================\n";

        std::cout << "1. Generate C++ Class\n";
        std::cout << "2. Generate C++ Project\n";
        std::cout << "3. Generate Python Script\n";
        std::cout << "4. Generate HTML Page\n";
        std::cout << "5. View Template Library\n";
        std::cout << "6. View Generation History\n";
        std::cout << "0. Exit\n";
    }

    std::string GetName() {
        std::string name;

        std::cout << "Enter project or file name: ";
        std::cin >> name;

        return name;
    }

    void Process(int choice) {
        switch (choice) {
        case 1:
            generator.GenerateCpp(GetName());
            break;

        case 2:
            generator.GenerateCppProject(GetName());
            break;

        case 3:
            generator.GeneratePython(GetName());
            break;

        case 4:
            generator.GenerateHTML(GetName());
            break;

        case 5:
            generator.DisplayTemplates();
            break;

        case 6:
            generator.DisplayHistory();
            break;

        case 0:
            running = false;
            std::cout << "\nNsonEngine shutting down.\n";
            break;

        default:
            std::cout << "Unknown operation.\n";
            break;
        }
    }
};

}

int main() {
    NsonEngine::NsonCore engine;
    engine.Run();

    return 0;
}
